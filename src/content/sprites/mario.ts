const padTop = (rows: readonly string[], total: number): string[] => [
  ...Array.from({ length: total - rows.length }, () => '.'.repeat(16)),
  ...rows,
];

/** Walk-1 bobs the head down a pixel: pad a row on top, shorter body below. */
const walkBob = (head: readonly string[], body: readonly string[]): string[] =>
  padTop([...head, ...body], head.length + body.length + 1);

