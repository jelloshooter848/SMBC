const modules: Record<string, readonly string[]> = { W: wall, C: crenel, N: window, T: doorTop, D: doorBody };

/** Lay 16x16 modules on a grid ('.' = empty) and add a dark edge wherever the building meets the sky. */
function compose(layout: string[]): string[] {
  const rows: string[][] = [];
  for (const line of layout) {
    for (let y = 0; y < 16; y++) {
      const row: string[] = [];
      for (const key of line) {
        const m = modules[key];
        row.push(...(m ? (m[y] as string) : '................'));
      }
      rows.push(row);
    }
  }
  const at = (x: number, y: number): string => rows[y]?.[x] ?? '.';
  return rows.map((row, y) =>
    row
      .map((c, x) =>
        c !== '.' && (at(x - 1, y) === '.' || at(x + 1, y) === '.' || at(x, y - 1) === '.') ? '6' : c,
      )
      .join(''),
  );
}

