const drawn = (name: string): readonly string[] => DRAWN.frames[name] as readonly string[];
const mirror = (rows: readonly string[]): string[] => rows.map((r) => r.split('').reverse().join(''));
const flipY = (rows: readonly string[]): string[] => [...rows].reverse();

/** Star power (PS-C19): four body colours over the same frames, like every Classic hero. */
const STAR_BODIES = [NES.white, NES.orange, NES.green, NES.redBright] as const;
const starPalettes: Record<string, string[]> = {};
STAR_BODIES.forEach((c, i) => {
  const base = yoshiPalettes.yoshi as string[];
  starPalettes[`yoshi-star-${i}`] = base.map((x, k) => (k === 1 ? c : k === 6 ? NES.black : x));
});
Object.assign(yoshiPalettes, starPalettes);

