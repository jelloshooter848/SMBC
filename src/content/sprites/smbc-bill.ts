const C = BILL_SMBC_CANVAS;
const at = (...layers: SmbcLayer[]): string[] => anchored(C, ...layers);
/** A torso (its BillTorsoMc top-left from the torso origin 16 px up) over a pair of legs. */
const body = (torso: SmbcLayer, legs: SmbcLayer, ...more: SmbcLayer[]): string[] =>
  at(legs, [torso[0], torso[1], torso[2] - 16], ...more);

const stand = (x: number, legs: readonly string[] = legsStand): SmbcLayer => [legs, x, -19];
const climb0 = at([climb, -9.5, -39]);

